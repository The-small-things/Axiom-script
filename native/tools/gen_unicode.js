// gen_unicode.js — write unicode.h, the tables ustr.c needs to change case as the reference
// does: String.prototype.toUpperCase / toLowerCase of every code point, as this Node's ICU
// computes them, plus the Cased and Case_Ignorable properties the final-sigma rule reads.
// usage: node tools/gen_unicode.js > unicode.h     (difftest.sh checks it is current)
'use strict';

const MAX = 0x110000;
const isSurrogate = (c) => c >= 0xd800 && c <= 0xdfff;

// Single code point mappings, compressed into runs: start..end with a stride of 1 or 2, every
// member mapping to itself + delta (A-Z is one run, Ā ā Ă ă … another).
function singleRuns(map) {
  const cps = [...map.keys()].sort((a, b) => a - b);
  const runs = [];
  for (const c of cps) {
    const d = map.get(c) - c;
    const r = runs[runs.length - 1];
    if (r && r.delta === d) {
      if (r.end === r.start && (c - r.end === 1 || c - r.end === 2)) { r.step = c - r.end; r.end = c; continue; }
      if (r.end !== r.start && c - r.end === r.step) { r.end = c; continue; }
    }
    runs.push({ start: c, end: c, step: 1, delta: d });
  }
  return runs;
}

function caseTables(fn) {
  const single = new Map();
  const multi = [];
  for (let c = 0; c < MAX; c++) {
    if (isSurrogate(c)) continue;
    const s = String.fromCodePoint(c);
    const m = s[fn]();
    if (m === s) continue;
    const cps = [...m].map((x) => x.codePointAt(0));
    if (cps.length === 1) single.set(c, cps[0]);
    else multi.push([c, cps]);
  }
  return { runs: singleRuns(single), multi };
}

function ranges(re) {
  const out = [];
  let start = -1;
  for (let c = 0; c <= MAX; c++) {
    const inSet = c < MAX && !isSurrogate(c) && re.test(String.fromCodePoint(c));
    if (inSet && start < 0) start = c;
    if (!inSet && start >= 0) { out.push([start, c - 1]); start = -1; }
  }
  return out;
}

const hex = (n) => '0x' + n.toString(16).toUpperCase();
const lines = [
  '// unicode.h — generated by tools/gen_unicode.js from Node ' + process.version + ' (Unicode ' +
    process.versions.unicode + ', ICU ' + process.versions.icu + '); do not edit.',
  '',
  'typedef struct { uint32_t start, end; uint8_t step; int32_t delta; } UcRun;',
  'typedef struct { uint32_t cp; uint8_t n; uint32_t out[3]; } UcMulti;',
  'typedef struct { uint32_t lo, hi; } UcRange;',
  '',
];
for (const [name, fn] of [['UPPER', 'toUpperCase'], ['LOWER', 'toLowerCase']]) {
  const { runs, multi } = caseTables(fn);
  lines.push(`static const UcRun UC_${name}_RUNS[] = {`);
  for (const r of runs) lines.push(`  { ${hex(r.start)}, ${hex(r.end)}, ${r.step}, ${r.delta} },`);
  lines.push('};', `#define UC_${name}_RUNS_N ${runs.length}`);
  lines.push(`static const UcMulti UC_${name}_MULTI[] = {`);
  for (const [c, cps] of multi) lines.push(`  { ${hex(c)}, ${cps.length}, { ${cps.map(hex).join(', ')} } },`);
  lines.push('};', `#define UC_${name}_MULTI_N ${multi.length}`, '');
}
for (const [name, re] of [['CASED', /\p{Cased}/u], ['CASE_IGNORABLE', /\p{Case_Ignorable}/u]]) {
  const rs = ranges(re);
  lines.push(`static const UcRange UC_${name}[] = {`);
  for (let i = 0; i < rs.length; i += 4) lines.push('  ' + rs.slice(i, i + 4).map(([a, b]) => `{ ${hex(a)}, ${hex(b)} }`).join(', ') + ',');
  lines.push('};', `#define UC_${name}_N ${rs.length}`, '');
}
process.stdout.write(lines.join('\n'));
